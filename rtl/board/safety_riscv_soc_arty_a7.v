// -----------------------------------------------------------------------------
// Arty A7-100T board wrapper for the safety-oriented RISC-V SoC
//
// Target:
//   FPGA : XC7A100T-1CSG324 (Digilent Arty A7-100T)
//   Clock: 100 MHz oscillator, 50 MHz SoC clock from the MMCM
//
// Firmware (default): fw/images/stage5_battery_monitor_demo.vmem
//   The battery-monitoring application. It reads the requested runtime
//   profile from SW1..SW0 and reconfigures the SoC whenever they change.
//
// Board controls
//   RESET button : system reset (active low)
//   SW1, SW0     : runtime profile request
//                    00 Basic       (DCLS off, supervision on)
//                    01 Safety      (DCLS on, fault injection not permitted)
//                    10 Diagnostic  (DCLS on, fault injection permitted)
//   SW3          : arm fault injection
//   BTN0         : inject Tier 2 fault in the instruction word of Core B
//   BTN1         : inject Tier 2 fault in the read data of Core B
//   BTN2         : inject Tier 1 fault at the comparison logic
//                    SW2 = 0 instruction address, SW2 = 1 data address
//   BTN3         : inject execution stall (emulated processor hang)
//
// Board indicators
//   LD4 (led[0]) : application heartbeat, blinks while the firmware runs
//   LD5 (led[1]) : DCLS comparison enabled
//   LD6 (led[2]) : fault latched
//   LD7 (led[3]) : safe state (both cores held in reset)
//   LD0 RGB      : green = healthy, red = fault latched
//   LD1 RGB      : blue = injection permitted, red = injection applied
//   LD2 RGB      : fault code, red = bit 0, green = bit 1, blue = bit 2
//   LD3 RGB      : profile, blue = Basic, green = Safety, red = Diagnostic
//   UART         : 115200 baud, 8N1, status text (see demo_status_reporter.v)
//
// The demo logic in this file only drives the SoC's existing fault-injection
// inputs and observes its status outputs.
//
// RTL language: Verilog
// -----------------------------------------------------------------------------

// Absolute firmware image paths, generated by scripts/vivado/create_project.tcl
`include "fw_images.vh"

module safety_riscv_soc_arty_a7 #(
    parameter         MemInitFile        = `FW_STAGE5_BATTERY_MONITOR_DEMO,
    // 50 MHz / 115200 baud
    parameter integer UART_CLKS_PER_BIT  = 434,
    // 2^19 cycles at 50 MHz = 10.5 ms
    parameter integer DEBOUNCE_BITS      = 19,
    // 2^27 cycles at 50 MHz = 2.7 s
    parameter integer STATUS_PERIOD_BITS = 27,
    // Heartbeat sequence bit shown on LD4
    parameter integer HEARTBEAT_LED_BIT  = 18
) (
    input  wire       clk,
    input  wire       reset,

    input  wire [3:0] sw,
    input  wire [3:0] btn,

    output wire [3:0] led,
    output wire [3:0] led_r,
    output wire [3:0] led_g,
    output wire [3:0] led_b,

    output wire       uart_tx
);

    wire clk_50mhz;
    wire soc_reset_n;

    wire [1:0]  selected_profile;
    wire        profile_valid;
    wire        dcls_enable;
    wire        fault_injection_enable;

    wire        mmio_interlock_hold;
    wire        mmio_interlock_fault;

    wire        dcls_instr_mismatch;
    wire        dcls_data_mismatch;
    wire        dcls_mismatch;

    wire        fault_latched;
    wire        instr_fault_seen;
    wire        data_fault_seen;
    wire        supervisor_fault_seen;
    wire        mmio_replica_integrity_fault_seen;
    wire [7:0]  fault_code;

    wire        safe_state_req;
    wire        watchdog_early_fault;
    wire        watchdog_timeout_fault;
    wire        progress_timeout_fault;
    wire        supervisor_fault;

    wire [31:0] heartbeat_value;
    wire        heartbeat_update;

    // -------------------------------------------------------------------------
    // Clock and reset
    //
    // The SoC stays in reset until the MMCM locks; reset release is
    // synchronized to the generated 50 MHz clock.
    // -------------------------------------------------------------------------
    arty_a7_clock_50mhz u_board_clock (
        .clk_100mhz    (clk),
        .reset_n       (reset),
        .clk_50mhz     (clk_50mhz),
        .reset_50mhz_n (soc_reset_n)
    );

    // -------------------------------------------------------------------------
    // Board inputs: synchronize and debounce
    // -------------------------------------------------------------------------
    wire [3:0] sw_level;
    wire [3:0] btn_rise;

    genvar gi;
    generate
        for (gi = 0; gi < 4; gi = gi + 1) begin : gen_sw
            board_input_debounce #(
                .COUNTER_BITS (DEBOUNCE_BITS)
            ) u_sw (
                .clk_i   (clk_50mhz),
                .rst_ni  (soc_reset_n),
                .raw_i   (sw[gi]),
                .level_o (sw_level[gi]),
                .rise_o  ()
            );
        end
        for (gi = 0; gi < 4; gi = gi + 1) begin : gen_btn
            board_input_debounce #(
                .COUNTER_BITS (DEBOUNCE_BITS)
            ) u_btn (
                .clk_i   (clk_50mhz),
                .rst_ni  (soc_reset_n),
                .raw_i   (btn[gi]),
                .level_o (),
                .rise_o  (btn_rise[gi])
            );
        end
    endgenerate

    // -------------------------------------------------------------------------
    // Manual fault-injection control
    // -------------------------------------------------------------------------
    wire [1:0]  tier1_target;
    wire [31:0] tier1_mask;
    wire [2:0]  tier2_target;
    wire [31:0] tier2_mask;

    wire        exec_stall;

    wire        inject_event;
    wire        inject_active;
    wire [2:0]  inject_select;
    wire [15:0] inject_latency;

    demo_fault_injection_ctrl u_fault_injection_ctrl (
        .clk_i                 (clk_50mhz),
        .rst_ni                (soc_reset_n),
        .arm_i                 (sw_level[3]),
        .variant_i             (sw_level[2]),
        .trigger_i             (btn_rise),
        .injection_permitted_i (fault_injection_enable),
        .fault_latched_i       (fault_latched),
        .tier1_target_o        (tier1_target),
        .tier1_mask_o          (tier1_mask),
        .tier2_target_o        (tier2_target),
        .tier2_mask_o          (tier2_mask),
        .exec_stall_o          (exec_stall),
        .inject_event_o        (inject_event),
        .inject_active_o       (inject_active),
        .inject_select_o       (inject_select),
        .latency_o             (inject_latency)
    );

    // -------------------------------------------------------------------------
    // Safety-oriented SoC
    // -------------------------------------------------------------------------
    safety_riscv_soc_stage4f #(
        .MemInitFile(MemInitFile)
    ) u_safety_riscv_soc (
        .clk_i                              (clk_50mhz),
        .rst_ni                             (soc_reset_n),

        .fault_inject_target_i              (tier1_target),
        .fault_inject_mask_i                (tier1_mask),
        .core_b_response_fault_inject_target_i (tier2_target),
        .core_b_response_fault_inject_mask_i   (tier2_mask),
        .exec_stall_inject_i                (exec_stall),
        .board_ctrl_i                       ({6'b000000, sw_level[1:0]}),

        .selected_profile_o                 (selected_profile),
        .profile_valid_o                    (profile_valid),
        .dcls_enable_o                       (dcls_enable),
        .fault_injection_enable_o            (fault_injection_enable),

        .mmio_interlock_hold_o              (mmio_interlock_hold),
        .mmio_interlock_fault_o              (mmio_interlock_fault),

        .dcls_instr_mismatch_o               (dcls_instr_mismatch),
        .dcls_data_mismatch_o                (dcls_data_mismatch),
        .dcls_mismatch_o                     (dcls_mismatch),

        .fault_latched_o                    (fault_latched),
        .instr_fault_seen_o                 (instr_fault_seen),
        .data_fault_seen_o                  (data_fault_seen),
        .supervisor_fault_seen_o            (supervisor_fault_seen),
        .core_a_double_fault_seen_o         (),
        .core_b_double_fault_seen_o         (),
        .mmio_replica_integrity_fault_seen_o (mmio_replica_integrity_fault_seen),
        .fault_code_o                       (fault_code),

        .safe_state_req_o                   (safe_state_req),
        .watchdog_early_fault_o             (watchdog_early_fault),
        .watchdog_timeout_fault_o           (watchdog_timeout_fault),
        .progress_timeout_fault_o           (progress_timeout_fault),
        .supervisor_fault_o                 (supervisor_fault),

        .heartbeat_value_o                 (heartbeat_value),
        .heartbeat_update_o                 (heartbeat_update)
    );

    // -------------------------------------------------------------------------
    // UART status reporter
    // -------------------------------------------------------------------------
    wire [7:0] tx_data;
    wire       tx_valid;
    wire       tx_ready;

    demo_status_reporter #(
        .STATUS_PERIOD_BITS (STATUS_PERIOD_BITS)
    ) u_status_reporter (
        .clk_i              (clk_50mhz),
        .rst_ni             (soc_reset_n),
        .status_request_i   (1'b0),
        .inject_event_i     (inject_event),
        .profile_i          (selected_profile),
        .dcls_enable_i      (dcls_enable),
        .injection_enable_i (fault_injection_enable),
        .fault_latched_i    (fault_latched),
        .fault_code_i       (fault_code),
        .safe_state_i       (safe_state_req),
        .heartbeat_i        (heartbeat_value),
        .inject_select_i    (inject_select),
        .inject_active_i    (inject_active),
        .latency_i          (inject_latency),
        .tx_data_o          (tx_data),
        .tx_valid_o         (tx_valid),
        .tx_ready_i         (tx_ready)
    );

    uart_tx #(
        .CLKS_PER_BIT (UART_CLKS_PER_BIT)
    ) u_uart_tx (
        .clk_i   (clk_50mhz),
        .rst_ni  (soc_reset_n),
        .data_i  (tx_data),
        .valid_i (tx_valid),
        .ready_o (tx_ready),
        .tx_o    (uart_tx)
    );

    // -------------------------------------------------------------------------
    // Indicators
    // -------------------------------------------------------------------------
    // The heartbeat sequence advances every few microseconds. One of its
    // higher bits blinks slowly enough to see, and freezes when the firmware
    // stops.
    assign led[0] = heartbeat_value[HEARTBEAT_LED_BIT];
    assign led[1] = dcls_enable;
    assign led[2] = fault_latched;
    assign led[3] = safe_state_req;

    // The RGB LEDs are very bright; drive them at 1/8 duty cycle.
    reg [15:0] dim_count_q;
    wire       dim;

    always @(posedge clk_50mhz or negedge soc_reset_n) begin
        if (!soc_reset_n)
            dim_count_q <= 16'd0;
        else
            dim_count_q <= dim_count_q + 16'd1;
    end

    assign dim = (dim_count_q[15:13] == 3'b000);

    // LD0: health
    assign led_g[0] = dim && profile_valid && !fault_latched;
    assign led_r[0] = dim && fault_latched;
    assign led_b[0] = 1'b0;

    // LD1: fault injection
    assign led_b[1] = dim && fault_injection_enable && !inject_active;
    assign led_r[1] = dim && inject_active;
    assign led_g[1] = 1'b0;

    // LD2: fault code bits 2..0
    assign led_r[2] = dim && fault_code[0];
    assign led_g[2] = dim && fault_code[1];
    assign led_b[2] = dim && fault_code[2];

    // LD3: runtime profile
    assign led_b[3] = dim && (selected_profile == 2'b00);
    assign led_g[3] = dim && (selected_profile == 2'b01);
    assign led_r[3] = dim && (selected_profile == 2'b10);

endmodule
